import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import process from 'node:process';

const pnpmEntry = process.env.npm_execpath;
if (!pnpmEntry) throw new Error('Run this generator through pnpm so npm_execpath is available.');
const result = spawnSync(process.execPath, [pnpmEntry, 'licenses', 'list', '--prod', '--json'], {
  cwd: process.cwd(),
  encoding: 'utf8',
});
if (result.status !== 0) throw new Error(result.stderr || 'Unable to read dependency licenses.');

const groups = JSON.parse(result.stdout);
const dependencies = Object.entries(groups)
  .flatMap(([license, entries]) =>
    entries.map((entry) => ({
      name: entry.name,
      versions: entry.versions.join(', '),
      license,
      homepage: entry.homepage || '',
    })),
  )
  .sort(
    (left, right) =>
      left.name.localeCompare(right.name) || left.versions.localeCompare(right.versions),
  );

const lines = [
  '# Third-Party Notices',
  '',
  '> Generated by `pnpm third-party:report`. Dependency versions come from the lockfile-resolved production graph.',
  '',
  '## Content sources',
  '',
  'AgentPrep publishes original sample content under CC BY 4.0 and a separately attributed Computer Network dataset transformed from a pinned external source.',
  '',
  'The Computer Network dataset is transformed by a dedicated importer from `https://github.com/lij768423-svg/408-` commit `267d0d815b1eee770dad12e88bbd560d08ba3f66`. AgentPrep does not copy the upstream application code and preserves source, transform, review, and license metadata for imported items.',
  '',
  '牛客、ky408、CodeBrick 等没有明确再分发授权的内容不得进入本仓库。',
  '',
  '## Production dependencies',
  '',
  '| Package | Version(s) | License | Homepage |',
  '| --- | --- | --- | --- |',
  ...dependencies.map(
    ({ name, versions, license, homepage }) =>
      `| ${name} | ${versions} | ${license} | ${homepage ? `[link](${homepage})` : ''} |`,
  ),
  '',
  'Full license texts remain available in each installed package and its linked upstream repository.',
  '',
];
const output = lines.join('\n');
const target = path.resolve('THIRD_PARTY_NOTICES.md');

if (process.argv.includes('--write')) {
  await writeFile(target, output, 'utf8');
  process.stdout.write(`Wrote ${target}\n`);
} else if (process.argv.includes('--check')) {
  const existing = await readFile(target, 'utf8').catch(() => '');
  if (existing !== output)
    throw new Error('Third-party notices are stale. Run pnpm third-party:report.');
  process.stdout.write('Third-party notices match the production dependency graph.\n');
} else {
  process.stdout.write(output);
}
